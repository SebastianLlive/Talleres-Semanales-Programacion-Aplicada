
package Practica5Hilos;

public class Mecanico {

    private int codigo;
    private String nombre;

    public Mecanico(int codigo, String nombre) {

        this.codigo = codigo;
        this.nombre = nombre;
    }

    public int getCodigo() {
        return codigo;
    }

    public String getNombre() {
        return nombre;
    }
}
